
def saludar(nombre):
    print(f"Hola, {nombre}")


saludar("Laura")
saludar("Andrés")


def mostrar_producto(nombre, cantidad):
    print(f"Producto: {nombre}")
    print(f"Existencias: {cantidad}")


mostrar_producto("Teclado", 4)
mostrar_producto("Mouse", 7)



